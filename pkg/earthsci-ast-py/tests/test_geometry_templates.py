"""The convex overlap-area templates of ``lib/geometry.esm`` against reference
areas.

Every polygon pair of ``tests/conformance/geometry_templates/pairs.json`` (the
cell pairs the repository's polygon and regridding documents clip, generated by
``scripts/gen-geometry-template-pairs.py``) runs through the expanded template
(``overlap_area_planar``, or ``overlap_area_spherical`` over unit vectors built
with ``lonlat_to_unit``) by the numpy interpreter. The template must agree with
the pair's exact / 40-digit reference area within the CONFORMANCE_SPEC §5.8.2
tolerance, give the planar reference exactly on a pair of cells from one grid,
and give the same bits on the padded copy of every group (repeated vertices
contribute exactly zero).
"""

from __future__ import annotations

import json
import math
import struct
from functools import cache
from typing import Any

import numpy as np
import pytest
from conftest import CONFORMANCE_DIR, REPO_ROOT

from earthsci_ast import load_string
from earthsci_ast.inline_tests import run_inline_tests
from earthsci_ast.numpy_interpreter import (
    EvalContext,
    eval_expr,
    refuse_unevaluable_operators,
)

GEOMETRY_LIBRARY = REPO_ROOT / "lib" / "geometry.esm"
PAIRS = json.loads((CONFORMANCE_DIR / "geometry_templates" / "pairs.json").read_text())
RTOL = PAIRS["tolerance"]["rtol"]
ATOL_FACTOR = PAIRS["tolerance"]["atol_factor"]


def _const(v: Any) -> dict:
    return {"op": "const", "args": [], "value": v}


def _bits(x: float) -> bytes:
    return struct.pack("<d", x)


def _doc(rhs: list[dict], imports: bool) -> dict:
    """A model whose i-th equation is ``D(out_i) = rhs[i]``, importing
    ``lib/geometry.esm`` when ``imports``."""
    variables = {
        f"out_{i}": {"type": "unknown", "default": 0.0, "units": "1"} for i in range(len(rhs))
    }
    equations = [
        {"lhs": {"op": "D", "args": [f"out_{i}"], "wrt": "t"}, "rhs": r} for i, r in enumerate(rhs)
    ]
    model: dict = {"variables": variables, "equations": equations}
    if imports:
        model["expression_template_imports"] = [{"ref": str(GEOMETRY_LIBRARY)}]
    return {
        "esm": "1.1.0",
        "metadata": {"name": "geometry_template_probe"},
        "models": {"Probe": model},
    }


def _apply(name: str, bindings: dict) -> dict:
    return {"op": "apply_expression_template", "args": [], "name": name, "bindings": bindings}


def _load_rhs(rhs: list[dict], imports: bool) -> list:
    """The loaded right-hand sides (one load: the library is schema-validated on
    every import, which dominates for a library this size)."""
    return [eq.rhs for eq in load_string(json.dumps(_doc(rhs, imports))).models["Probe"].equations]


def _faq(out: list, ranges: dict, expr: dict) -> dict:
    return {"op": "faq", "args": [], "output_idx": out, "ranges": ranges, "expr": expr}


def _unit_stack_expr(stack: list) -> dict:
    """The ``[cells, verts, 3]`` unit-vector stack of a lon-lat stack: a ``faq``
    over ``lonlat_to_unit``."""
    return _faq(
        ["c", "v", "d"],
        {"c": [1, len(stack)], "v": [1, len(stack[0])], "d": [1, 3]},
        _apply("lonlat_to_unit", {"ring": _const(stack), "cell": "c", "vert": "v", "comp": "d"}),
    )


def _atol(group: dict) -> float:
    if group["manifold"] != "planar":
        return ATOL_FACTOR
    coords = [
        abs(x) for stack in (group["ring_a"], group["ring_b"]) for r in stack for p in r for x in p
    ]
    return ATOL_FACTOR * max(1.0, max(coords)) ** 2


def _as_list(expr) -> list:
    """An array-valued expression (a ``faq`` with output indices) evaluated by
    the numpy interpreter, as nested lists; ``evaluate`` is scalar-only."""
    refuse_unevaluable_operators(expr)
    ctx = EvalContext(
        state_layout={},
        state_shapes={},
        param_values={},
        observed_values={},
        y=np.empty((0,), dtype=float),
        t=0.0,
    )
    return np.asarray(eval_expr(expr, ctx), dtype=float).tolist()


@cache
def _template_values() -> dict[str, tuple[float, ...]]:
    """Template area of every pair, by group id: per group one ``faq`` over every
    cell pair applying the template once, so the library is expanded once per
    group rather than once per pair. A spherical group's unit-vector stacks are
    themselves ``faq`` expansions of ``lonlat_to_unit``."""
    groups = PAIRS["groups"]
    spherical = [g for g in groups if g["manifold"] != "planar"]
    stack_exprs = []
    for g in spherical:
        stack_exprs += [_unit_stack_expr(g["ring_a"]), _unit_stack_expr(g["ring_b"])]
    stacks_flat = iter(_as_list(e) for e in _load_rhs(stack_exprs, imports=True))
    stacks = {g["id"]: (next(stacks_flat), next(stacks_flat)) for g in spherical}
    exprs = []
    for g in groups:
        if g["manifold"] == "planar":
            name, ra, rb = "overlap_area_planar", g["ring_a"], g["ring_b"]
        else:
            name, (ra, rb) = "overlap_area_spherical", stacks[g["id"]]
        call = _apply(
            name,
            {
                "ring_a": _const(ra),
                "cell_a": "i",
                "nv_a": g["nv_a"],
                "ring_b": _const(rb),
                "cell_b": "j",
                "nv_b": g["nv_b"],
            },
        )
        exprs.append(
            _faq(["i", "j"], {"i": [1, len(g["ring_a"])], "j": [1, len(g["ring_b"])]}, call)
        )
    out = {}
    for g, e in zip(groups, _load_rhs(exprs, imports=True)):
        table = _as_list(e)
        out[g["id"]] = tuple(float(table[p["i"] - 1][p["j"] - 1]) for p in g["pairs"])
    return out


_GROUP_IDS = [g["id"] for g in PAIRS["groups"]]


@pytest.mark.parametrize("gid", _GROUP_IDS, ids=_GROUP_IDS)
def test_template_agrees_with_reference(gid: str):
    group = next(g for g in PAIRS["groups"] if g["id"] == gid)
    values = _template_values()[gid]
    atol = _atol(group)
    failures: list[str] = []
    for pair, t in zip(group["pairs"], values):
        label = f"({pair['i']},{pair['j']})"
        ref = pair["reference"]
        if not math.isfinite(t):
            failures.append(f"{label}: template gives {t!r}")
            continue
        if ref is not None and abs(t - ref) > atol + RTOL * abs(ref):
            failures.append(f"{label}: template {t!r} vs reference {ref!r}")
        if (
            pair["same_grid"]
            and group["manifold"] == "planar"
            and ref is not None
            and _bits(t) != _bits(ref)
        ):
            failures.append(f"{label}: same-grid pair not exact: template {t!r}, reference {ref!r}")
    assert not failures, f"{gid}: " + "; ".join(failures)


@pytest.mark.parametrize(
    "gid",
    [g["id"] for g in PAIRS["groups"] if "padding_of" in g],
    ids=[g["id"] for g in PAIRS["groups"] if "padding_of" in g],
)
def test_padding_contributes_exactly_zero(gid: str):
    group = next(g for g in PAIRS["groups"] if g["id"] == gid)
    padded = _template_values()[gid]
    plain = _template_values()[group["padding_of"]]
    mismatched = [
        f"({p['i']},{p['j']}): {a!r} vs {b!r}"
        for p, a, b in zip(group["pairs"], padded, plain)
        if _bits(a) != _bits(b)
    ]
    assert not mismatched, f"{gid}: " + "; ".join(mismatched)


def _lonlat_to_unit(lon_deg: float, lat_deg: float) -> tuple[float, float, float]:
    """``(cos(lat) cos(lon), cos(lat) sin(lon), sin(lat))``, degrees converted
    by the binary64 constant pi/180, in the template's operation order."""
    lon = lon_deg * 0.017453292519943295
    lat = lat_deg * 0.017453292519943295
    return (math.cos(lat) * math.cos(lon), math.cos(lat) * math.sin(lon), math.sin(lat))


def test_lonlat_to_unit_is_the_spherical_conversion():
    """``lonlat_to_unit`` gives the bits of the lon-lat to unit-vector
    conversion it documents."""
    ring = [[[0.0, 0.0], [30.0, 45.0], [-120.5, -60.25], [179.9, 89.0]]]
    (expr,) = _load_rhs([_unit_stack_expr(ring)], imports=True)
    got = _as_list(expr)[0]
    for (lon, lat), vec in zip(ring[0], got):
        want = _lonlat_to_unit(lon, lat)
        assert [_bits(x) for x in vec] == [_bits(x) for x in want], (lon, lat, vec, want)


_TIER_FIXTURES = sorted((CONFORMANCE_DIR / "geometry_templates" / "fixtures").glob("*.esm"))


@pytest.mark.parametrize("compiler", ["interpreter", "native"])
@pytest.mark.parametrize("path", _TIER_FIXTURES, ids=[p.stem for p in _TIER_FIXTURES])
def test_geometry_templates_tier_documents(path, compiler):
    """The ``geometry_templates`` tier documents pass their own inline tests
    (the tier is not in the cross-binding gate until every native compiler
    builds them)."""
    results = run_inline_tests(str(path), compiler=compiler)
    assert results
    failed = [
        f"{r.test_id}#{r.assertion_idx} {r.variable}: {r.actual!r} vs {r.expected!r}"
        for r in results
        if not r.passed
    ]
    assert not failed, "; ".join(failed)

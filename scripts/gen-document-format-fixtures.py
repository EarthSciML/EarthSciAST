def species_list(*terms):
    return [{"species": n, "stoichiometry": c} for n, c in terms]


def chem_doc(reactions, species=("NO", "NO2", "O3"), extra=None):
    rs = {
        "species": {n: {"default": 0} for n in species},
        "parameters": {"k_1": {"default": 1.8e-12, "units": "1/s"}, "j": {"default": 0.01}},
        "reactions": reactions,
    }
    if extra:
        rs.update(extra)
    return document(reaction_systems={"Chem": rs})



# The generator.


class Area:
    def __init__(self, name, title):
        self.name = name
        self.title = title
        self.cases = []


class Gen:
    def __init__(self, lean):
        self.lean = lean
        self.ids = set()

    def _id(self, cid):
        if cid in self.ids:
            raise SystemExit(f"duplicate case id {cid}")
        self.ids.add(cid)

    def printed(self, area, cid, description, doc, math=False, written=False):
        """Both printed texts of a document, each checked to read back as the document.
        `written`: keep the document as written too, for a case about the canonical form."""
        self._id(cid)
        esm = self.lean.canon(doc)
        case = {"id": cid, "kind": "print", "description": description}
        if written:
            case["written"] = doc
        case["esm"] = esm
        texts = {}
        for s in SURFACES:
            text = self.lean.print(s, esm)
            back = self.lean.parse(s, text)
            if back is None or not same(back, esm):
                raise SystemExit(f"{cid}: the {s} text does not read back as the document")
            texts[s] = text
        if math:
            case["math"] = {
                "latex": equation_math("markdown", texts["markdown"]),
                "typst": equation_math("typst", texts["typst"]),
            }
        case["markdown"] = texts["markdown"]
        case["typst"] = texts["typst"]
        area.cases.append(case)
        return texts

    def _edit(self, cid, text, edits):
        for old, new in edits:
            if text.count(old) != 1:
                raise SystemExit(
                    f"{cid}: edit target {old!r} occurs {text.count(old)} times in:\n{text}"
                )
            text = text.replace(old, new)
        return text

    def variant(self, area, cid, description, doc, surface, edits=(), text=None, reads_as=None):
        """A hand-written spelling: the printed text with `edits` applied (or `text`), which
        must read as `reads_as` (default: the document itself)."""
        self._id(cid)
        esm = self.lean.canon(doc)
        canonical = self.lean.print(surface, esm)
        source = text if text is not None else self._edit(cid, canonical, edits)
        if source == canonical:
            raise SystemExit(f"{cid}: the variant input is the canonical text")
        expect = self.lean.canon(reads_as) if reads_as is not None else esm
        got = self.lean.parse(surface, source)
        if got is None:
            raise SystemExit(f"{cid}: esm-lean refuses the variant input:\n{source}")
        if not same(got, expect):
            raise SystemExit(f"{cid}: the variant reads as\n{enc(got)}\nnot\n{enc(expect)}")
        canon_expect = self.lean.print(surface, expect)
        area.cases.append(
            {
                "id": cid,
                "kind": "variant",
                "description": description,
                "surface": surface,
                "input": source,
                "esm": expect,
                "canonical": canon_expect,
            }
        )

    def refusal(self, area, cid, description, doc, surface, error, edits=(), text=None):
        """Input esm-lean refuses. `error` is the code a binding reports (README.md)."""
        self._id(cid)
        if text is None:
            text = self._edit(cid, self.lean.print(surface, self.lean.canon(doc)), edits)
        if self.lean.parse(surface, text) is not None:
            raise SystemExit(f"{cid}: esm-lean accepts the input it should refuse:\n{text}")
        area.cases.append(
            {
                "id": cid,
                "kind": "refusal",
                "description": description,
                "surface": surface,
                "input": text,
                "error": error,
            }
        )



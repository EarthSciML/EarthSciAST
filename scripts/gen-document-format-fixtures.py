"""Generate the document source format golden set from the Lean oracle.

The fixtures under `tests/conformance/document_format/` pin how an .esm document is
written as Markdown (LaTeX math) and as Typst, and how hand-written spellings and
malformed input are read. Every expected text and every expected JSON value in them is
produced here by `esm-lean` (formal/Adapter), the executable Lean model whose printers
and parsers carry the round-trip proofs; nothing is written by hand except the inputs.

    python3 scripts/gen-document-format-fixtures.py             # (re)write the fixtures
    python3 scripts/gen-document-format-fixtures.py --check     # fail if they are stale
    NODE_PATH=/path/to/node_modules \\
        python3 scripts/gen-document-format-fixtures.py --validate --typst /path/to/typst

`--esm-lean` (default `formal/.lake/build/bin/esm-lean`, after `lake build` in formal/)
names the oracle. `--check` regenerates in memory and compares with the committed files,
so a printer or parser change that moves a pinned spelling fails it.

`--validate` also renders what was printed, as the whole-corpus check
(formal/scripts/doc-corpus.py) does: every Typst document compiles with Typst against the
repository's `esm` package (typst/packages), and every piece of math in every Markdown
document renders in KaTeX in strict mode with mhchem (formal/scripts/katex-check.cjs,
which needs the `katex` npm package on NODE_PATH). It needs those tools and is not part
of `--check`.

The whole-corpus round trip (every .esm under tests/ through both formats) is run at
run time from the corpus itself and is never written here.
"""


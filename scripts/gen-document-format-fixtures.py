# Building blocks for the documents the cases are made of.


def document(models=None, reaction_systems=None, metadata=None, **top):
    d = {"esm": ESM, "metadata": metadata or {"name": "fixture"}}
    if models is not None:
        d["models"] = models
    if reaction_systems is not None:
        d["reaction_systems"] = reaction_systems
    d.update(top)
    return d


def params(*names, **typed):
    v = {n: {"type": "parameter"} for n in names}
    v.update(typed)
    return v


def expr_doc(rhs, names, lhs="y", index_sets=None, templates=None, extra_model=None):
    """One model, M: the names as parameters, `y` (or the name a derivative on the left
    differentiates) an unknown, and the equation lhs = rhs."""
    variables = params(*names)
    if lhs == "y":
        variables["y"] = {"type": "unknown"}
    elif isinstance(lhs, dict) and lhs.get("op") == "D":
        variables[lhs["args"][0]] = {"type": "unknown"}
    model = {"variables": variables, "equations": [{"lhs": lhs, "rhs": rhs}]}
    if templates:
        model["operators"] = templates
    if extra_model:
        model.update(extra_model)
    top = {}
    if index_sets:
        top["index_sets"] = index_sets
    return document(models={"M": model}, **top)


def op(name, *args, **fields):
    node = {"op": name, "args": list(args)}
    node.update(fields)
    return node


def const(value, units=None):
    node = {"op": "const", "args": [], "value": value}
    if units is not None:
        node["units"] = units
    return node


def idx(a, *i):
    return op("index", a, *i)


def faq(expr, ranges, output_idx=(), **fields):
    node = {"op": "faq", "args": [], "expr": expr, "ranges": ranges, "output_idx": list(output_idx)}
    node.update(fields)
    return node


def tmpl(name, **bindings):
    return {"op": "apply_operator", "args": [], "name": name, "bindings": bindings}



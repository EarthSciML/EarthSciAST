# --------------------------------------------------------------------------------------
# Extracting the equation's math from a printed document, for the readable `math` field.


def equation_math(surface, text):
    """The math of the first equation display of a printed document (not a template's)."""
    lines = text.split("\n")
    fence = False
    i = 0
    while i < len(lines):
        line = lines[i]
        if surface == "markdown" and line.startswith("```"):
            fence = line.startswith("```esm:") if not fence else False
        elif surface == "markdown" and not fence and line == "$$":
            j = lines.index("$$", i + 1)
            body = "\n".join(lines[i + 1 : j])
            if "\\coloneqq" not in body:
                return body
            i = j
        elif surface == "typst" and line.startswith("$ "):
            j = i
            while not lines[j].endswith(" $"):
                j += 1
            body = "\n".join(lines[i : j + 1])[2:-2]
            if ":=" not in body:
                return body
            i = j
        i += 1
    return None



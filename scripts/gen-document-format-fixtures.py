class LeanError(Exception):
    pass


class Num:
    """A JSON number as esm-lean spelled it (the canonical spelling, CONFORMANCE §5.5.3.1),
    so the fixtures keep `1.0e-8` rather than Python's `1e-08`."""

    def __init__(self, text):
        self.text = text


def loads(text):
    return json.loads(text, parse_float=Num, parse_int=Num)


def enc(v):
    """Compact JSON, numbers as spelled, keys in the order given (esm-lean sorts them)."""
    if isinstance(v, Num):
        return v.text
    if isinstance(v, dict):
        return "{" + ", ".join(f"{enc(k)}: {enc(x)}" for k, x in v.items()) + "}"
    if isinstance(v, (list, tuple)):
        return "[" + ", ".join(enc(x) for x in v) + "]"
    return json.dumps(v, ensure_ascii=False)


class Lean:
    """Runs esm-lean on small files in a private temporary directory."""

    def __init__(self, binary):
        self.binary = str(binary)
        self.dir = tempfile.mkdtemp(prefix="docfmt-")
        self.n = 0

    def close(self):
        shutil.rmtree(self.dir, ignore_errors=True)

    def _run(self, mode, text, suffix):
        self.n += 1
        path = os.path.join(self.dir, f"in{self.n}{suffix}")
        with open(path, "w", encoding="utf-8") as f:
            f.write(text)
        proc = subprocess.run([self.binary, mode, path], capture_output=True, text=True)
        os.unlink(path)
        return proc.returncode, proc.stdout, proc.stderr

    def canon(self, doc):
        rc, out, err = self._run("canon", enc(doc), ".esm")
        if rc:
            raise LeanError(f"canon failed: {err}")
        return loads(out)

    def print(self, surface, doc):
        mode = "print-md" if surface == "markdown" else "print-typ"
        rc, out, err = self._run(mode, enc(doc), ".esm")
        if rc:
            raise LeanError(f"{mode} failed: {err}")
        return out

    def parse(self, surface, text):
        """The canonical JSON a source text holds, or None when esm-lean refuses it."""
        mode, suffix = ("parse-md", ".md") if surface == "markdown" else ("parse-typ", ".typ")
        rc, out, err = self._run(mode, text, suffix)
        if rc == 1:
            return None
        if rc:
            raise LeanError(f"{mode} failed: {err}")
        return loads(out)



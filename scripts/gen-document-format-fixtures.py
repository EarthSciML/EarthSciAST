def used(e, pool=NAMES):
    """The names of `pool` an expression mentions, so a document declares only those."""
    found = set()

    def walk(v):
        if isinstance(v, str):
            if v in pool:
                found.add(v)
        elif isinstance(v, list):
            for x in v:
                walk(x)
        elif isinstance(v, dict):
            for x in v.values():
                walk(x)

    walk(e)
    return tuple(sorted(found))


